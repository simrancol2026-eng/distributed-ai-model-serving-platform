-- Sprint 2: persistent request lifecycle tracking.
-- One row per POST /api/inference request, keyed by the requestId the API already returns.
-- Lifecycle: RECEIVED -> DISPATCHED (a worker was chosen) -> SUCCEEDED | FAILED.
-- A request rejected before a worker is chosen goes RECEIVED -> FAILED.
-- The input text itself is NOT stored (only its length), so no user content is persisted.
-- Never edit this file after it has been applied: add V3__... instead.
-- Written to run unchanged on PostgreSQL and on H2 (PostgreSQL mode, tests only).

CREATE TABLE inference_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- arrival order
    request_id        CHAR(36)     NOT NULL,         -- UUID returned to the client as "requestId"
    status            VARCHAR(16)  NOT NULL,
    -- what the client asked for (as sent, trimmed and length-capped)
    capability        VARCHAR(16),
    requested_model   VARCHAR(64),
    requested_version VARCHAR(64),
    input_chars       INTEGER,                       -- length of "input"; the text is not stored
    -- what the platform decided (filled in when a worker is chosen)
    resolved_version  VARCHAR(64),                   -- registry label actually served (versioned requests)
    artifact          VARCHAR(200),
    artifact_revision VARCHAR(64),
    worker_endpoint   VARCHAR(255),                  -- host:port the request was sent to
    -- outcome
    worker_id         VARCHAR(100),                  -- id the worker reported in its answer (success only)
    http_status       INTEGER,
    error_code        VARCHAR(40),                   -- stable API error code, NULL on success
    total_ms          BIGINT,                        -- backend time from receipt to response
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dispatched_at     TIMESTAMP WITH TIME ZONE,
    completed_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_inference_requests_request_id UNIQUE (request_id),
    CONSTRAINT ck_inference_requests_status CHECK (status IN ('RECEIVED', 'DISPATCHED', 'SUCCEEDED', 'FAILED'))
);
