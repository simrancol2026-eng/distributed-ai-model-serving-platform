-- Sprint 2: model registry (models and their versions).
-- Applied once by Flyway on an empty database; Flyway records it in flyway_schema_history
-- and never re-runs it. Never edit this file after it has been applied: add V2__... instead.
-- Written to run unchanged on PostgreSQL and on H2 (PostgreSQL mode, tests only).

CREATE TABLE models (
    id          VARCHAR(64)   PRIMARY KEY,          -- stable slug, e.g. 'sentiment-distilbert'
    name        VARCHAR(200)  NOT NULL,
    task        VARCHAR(100)  NOT NULL,             -- e.g. 'sentiment-analysis'
    capability  VARCHAR(16)   NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_models_capability CHECK (capability IN ('TEXT', 'CODE', 'IMAGE', 'DOCUMENT'))
);

CREATE TABLE model_versions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id          VARCHAR(64)  NOT NULL,
    version           VARCHAR(64)  NOT NULL,        -- label chosen by the registrant, e.g. 'v1'
    artifact          VARCHAR(200) NOT NULL,        -- e.g. Hugging Face repo id
    artifact_revision CHAR(40)     NOT NULL,        -- full 40-hex immutable commit of the artifact
    framework         VARCHAR(100),
    notes             VARCHAR(1000),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_model_versions_model FOREIGN KEY (model_id) REFERENCES models (id),
    -- One label per model.
    CONSTRAINT uq_model_versions_label UNIQUE (model_id, version),
    -- The same artifact revision cannot be registered twice under different labels.
    CONSTRAINT uq_model_versions_artifact UNIQUE (model_id, artifact, artifact_revision)
);
